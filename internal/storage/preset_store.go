// ChatMessage represents a single turn in the post-generation refinement flow
type ChatMessage struct {
	Role    string `json:"role"` // "user" or "model"
	Content string `json:"content"`
}

// BlockParameter represents a single knob or slider value. Value is the canonical,
// editable value (Scene A / Rhythm) -- the editable workspace UI reads and writes this
// field only and has no scene awareness. ValueB is an optional Scene B / Lead override for
// the read-only preview table; when empty, rendering falls back to Value (same setting in
// both scenes).
type BlockParameter struct {
	Name   string `json:"name"`
	Type   string `json:"type"` // "slider", "toggle", "dropdown"
	Value  string `json:"value"`
	ValueB string `json:"value_b,omitempty"`
	Unit   string `json:"unit,omitempty"`
	// Basis discloses how confidently-real this parameter's Value is: "confirmed_range" (a
	// documented device min/max, e.g. Global EQ's published +-12dB), "real_gear_analog" (the
	// value mirrors a documented real-world amp/pedal setting), "engineering_convention" (a
	// standard, physically-reasonable value with no specific documented source), or "estimate"
	// (the model's best numeric judgment). Disclosure only -- never permission to omit, hedge,
	// or return a range instead of a decisive number; Value must always be real and usable.
	Basis string `json:"basis,omitempty"`
	// Evidence is set only on values read back from a Quad Cortex (Basis "device_readback"):
	// what backs the wire-to-display conversion, e.g. "taper:g4". Empty otherwise.
	Evidence string `json:"evidence,omitempty"`
}

// EffectBlock represents a single gear block in the signal chain
type EffectBlock struct {
	ID         string           `json:"id"`
	Type       string           `json:"type"` // e.g. "Amplifier", "Overdrive"
	Model      string           `json:"model"`
	Parameters []BlockParameter `json:"parameters"`
	// KeptDefaults names the block's device controls the Architect deliberately left at
	// their device default (it lists only changed controls in Parameters). Written by
	// catalog-aware Architect prompts; nil on older presets.
	KeptDefaults []string `json:"kept_defaults,omitempty"`
	Rationale    string   `json:"rationale,omitempty"`
}

// StructuredPreset wraps the signal chain per guitar variation
type StructuredPreset struct {
	Guitars map[string][]EffectBlock `json:"guitars"`
}

// Preset represents a saved configuration generated by the modeling pipeline
type Preset struct {
	ID               string        `json:"id"`
	Name             string        `json:"name"`
	Payload          string        `json:"payload"` // JSON string of StructuredPreset or legacy HTML map
	BuilderStatement string        `json:"builder_statement,omitempty"`
	ChatHistory      []ChatMessage `json:"chat_history,omitempty"`
	CreatedAt        string        `json:"created_at"`
	UpdatedAt        string        `json:"updated_at"`
	// RunIDs links the preset to the run log of the generate run that created
	// it, then each refine run that changed it (runs/<id>.json). Old presets
	// simply have none.
	RunIDs []string `json:"run_ids,omitempty"`
	// Origin is set on a preset that was not generated here (today: imported from a Quad
	// Cortex read-back). Nil on every generated preset.
	Origin *PresetOrigin `json:"origin,omitempty"`
}

// OriginDeviceReadback marks a draft imported from the unit's open preset (plan P5).
const OriginDeviceReadback = "device-readback"

// PresetOrigin records where a non-generated preset came from. Every string is already
// sanitized device text: data, never instructions.
type PresetOrigin struct {
	Kind       string `json:"kind"`
	JobID      string `json:"job_id,omitempty"`
	Slot       string `json:"slot,omitempty"`
	DeviceName string `json:"device_name,omitempty"`
	Firmware   string `json:"firmware,omitempty"`
	ReadAt     string `json:"read_at,omitempty"`
	Format     string `json:"format,omitempty"`
	// Unconverted counts the controls the import left out (listed in the draft's blocks).
	Unconverted int `json:"unconverted,omitempty"`
}

// Client defines the interface for underlying storage operations
type Client interface {
	ReadFile(ctx context.Context, bucket, object string) ([]byte, error)
	WriteFile(ctx context.Context, bucket, object string, data []byte) error
	ListFiles(ctx context.Context, bucket, prefix string) ([]string, error)
	DeleteFile(ctx context.Context, bucket, object string) error
	Close()
}

// PresetStore provides an interface to manage preset persistence
type PresetStore struct {
	client Client
	bucket string
	prefix string
	cache  []*Preset
	// mu guards cache only; it is never held across a storage call except by the one-time
	// load in List. idLocks serialises a preset's own storage write/delete and its cache
	// update, so operations on different presets (almost always) run in parallel and
	// readers (List) aren't stalled behind a slow write. A fixed set of stripes keyed by
	// a hash of the id keeps memory constant however many presets come and go; two ids
	// sharing a stripe only serialise, and no code path holds two stripes at once.
	mu      sync.RWMutex
	idLocks [idLockStripes]sync.Mutex
}

const idLockStripes = 256

// lockStripe is the stripe an id maps to.
func lockStripe(id string) int {
	h := fnv.New32a()
	h.Write([]byte(id))
	return int(h.Sum32() % idLockStripes)
}

// lockID takes the per-preset lock and returns its release func.
func (s *PresetStore) lockID(id string) func() {
	m := &s.idLocks[lockStripe(id)]
	m.Lock()
	return m.Unlock
}

// NewPresetStore creates a new generic preset store
func NewPresetStore(client Client, bucket string) *PresetStore {
	return &PresetStore{
		client: client,
		bucket: bucket,
		prefix: "presets/",
	}
}

// Bucket returns the bucket this store reads and writes.
func (s *PresetStore) Bucket() string { return s.bucket }

// Save creates or overwrites a preset
func (s *PresetStore) Save(ctx context.Context, p *Preset) error {
	if p.ID == "" {
		p.ID = uuid.New().String()
	}
	if p.CreatedAt == "" {
		p.CreatedAt = time.Now().UTC().Format(time.RFC3339)
	}
	p.UpdatedAt = time.Now().UTC().Format(time.RFC3339)

	data, err := json.Marshal(p)
	if err != nil {
		return err
	}

	objectName := fmt.Sprintf("%s%s.json", s.prefix, p.ID)

	// Held across the write and the cache update, so a concurrent Delete or DeleteIf of this
	// preset (the draft cleanup) can't land between them and leave storage and cache
	// disagreeing. Other presets are unaffected.
	defer s.lockID(p.ID)()

	if err := s.client.WriteFile(ctx, s.bucket, objectName, data); err != nil {
		return err
	}

	s.mu.Lock()
	defer s.mu.Unlock()
	if s.cache != nil {
		found := false
		for i, cached := range s.cache {
			if cached.ID == p.ID {
				s.cache[i] = p
				found = true
				break
			}
		}
		if !found {
			s.cache = append(s.cache, p)
		}
	}

	return nil
}

// Exists reports whether a preset with this id is stored, telling "not there" from a storage
// error (Get cannot: the backends have no not-found sentinel). It lists by the id as a
// prefix, because ListFiles skips an object whose key equals the prefix.
func (s *PresetStore) Exists(ctx context.Context, id string) (bool, error) {
	names, err := s.client.ListFiles(ctx, s.bucket, s.prefix+id)
	if err != nil {
		return false, err
	}
	want := fmt.Sprintf("%s%s.json", s.prefix, id)
	for _, n := range names {
		if n == want {
			return true, nil
		}
	}
	return false, nil
}

// Get retrieves a specific preset by ID
func (s *PresetStore) Get(ctx context.Context, id string) (*Preset, error) {
	objectName := fmt.Sprintf("%s%s.json", s.prefix, id)
	data, err := s.client.ReadFile(ctx, s.bucket, objectName)
	if err != nil {
		return nil, err
	}

	var p Preset
	if err := json.Unmarshal(data, &p); err != nil {
		return nil, err
	}
	return &p, nil
}

// listLoadTimeout bounds the one-time load of the whole bucket into the cache.
const listLoadTimeout = 60 * time.Second

// listReadWorkers is how many preset objects the initial load reads at once.
const listReadWorkers = 8

// List retrieves all presets currently saved.
//
// The first call loads every preset into an in-memory cache. That load is never cut short
// by the caller's context: a request deadline used to abort the remaining reads, which were
// skipped, and the shortened list was then cached until restart (a saved preset could be
// missing from every list while get-by-id still worked). It runs on its own timeout, and
// if any object can't be read nothing is cached and the error is returned, so the next
// call tries again.
func (s *PresetStore) List(ctx context.Context) ([]*Preset, error) {
	s.mu.RLock()
	if s.cache != nil {
		defer s.mu.RUnlock()
		return append([]*Preset(nil), s.cache...), nil
	}
	s.mu.RUnlock()

	s.mu.Lock()
	defer s.mu.Unlock()

	// Check again after acquiring write lock
	if s.cache != nil {
		return append([]*Preset(nil), s.cache...), nil
	}

	loadCtx, cancel := context.WithTimeout(context.WithoutCancel(ctx), listLoadTimeout)
	defer cancel()

	files, err := s.client.ListFiles(loadCtx, s.bucket, s.prefix)
	if err != nil {
		return nil, err
	}

	var names []string
	for _, f := range files {
		if strings.HasSuffix(f, ".json") {
			names = append(names, f)
		}
	}

	loaded := make([]*Preset, len(names))
	errs := make([]error, len(names))
	sem := make(chan struct{}, listReadWorkers)
	var wg sync.WaitGroup
	for i, f := range names {
		wg.Add(1)
		sem <- struct{}{}
		go func(i int, f string) {
			defer wg.Done()
			defer func() { <-sem }()
			data, err := s.client.ReadFile(loadCtx, s.bucket, f)
			if err != nil {
				errs[i] = fmt.Errorf("reading %s: %w", f, err)
				return
			}
			var p Preset
			if err := json.Unmarshal(data, &p); err != nil {
				// A corrupt object is skipped (and logged) rather than hiding every preset.
				log.Printf("preset store: skipping unreadable %s: %v", f, err)
				return
			}
			loaded[i] = &p
		}(i, f)
	}
	wg.Wait()

	for _, e := range errs {
		if e != nil {
			return nil, e // not cached: the next List retries the whole load
		}
	}

	var presets []*Preset
	for _, p := range loaded {
		if p != nil {
			presets = append(presets, p)
		}
	}
	if presets == nil {
		presets = []*Preset{} // loaded, just empty (a nil cache means "not loaded")
	}

	s.cache = presets
	return append([]*Preset(nil), presets...), nil
}

// Delete removes a preset from storage
func (s *PresetStore) Delete(ctx context.Context, id string) error {
	_, err := s.DeleteIf(ctx, id, nil)
	return err
}

// DeleteIf deletes a preset only if keep-or-delete says so about its current stored
// state: when check is non-nil it is given the preset as stored right now, and the delete
// happens only if it returns true. The read, the check and the delete run under the same
// per-preset lock as Save, so a rename can't slip in between (the draft cleanup used to delete a
// draft by id after a user had just named it). A preset that is already gone is not an
// error. It reports whether it deleted.
func (s *PresetStore) DeleteIf(ctx context.Context, id string, check func(*Preset) bool) (bool, error) {
	objectName := fmt.Sprintf("%s%s.json", s.prefix, id)

	defer s.lockID(id)()

	if check != nil {
		data, err := s.client.ReadFile(ctx, s.bucket, objectName)
		if err != nil {
			// The backends have no not-found sentinel, so ask the listing: gone is fine,
			// but a transient read failure must surface so the caller can retry.
			exists, lerr := s.Exists(ctx, id)
			if lerr != nil {
				return false, lerr
			}
			if !exists {
				return false, nil
			}
			return false, fmt.Errorf("reading preset %s for delete check: %w", id, err)
		}
		var p Preset
		if err := json.Unmarshal(data, &p); err != nil || !check(&p) {
			return false, nil
		}
	}

	if err := s.client.DeleteFile(ctx, s.bucket, objectName); err != nil {
		return false, err
	}

	s.mu.Lock()
	defer s.mu.Unlock()
	if s.cache != nil {
		for i, p := range s.cache {
			if p.ID == id {
				s.cache = append(s.cache[:i], s.cache[i+1:]...)
				break
			}
		}
	}

	return true, nil
}
